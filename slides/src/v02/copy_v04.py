def apply(n, sl):
    """Apply the v04 edits for physical slide n to the slide dict, in place."""
    body = sl["body"]
    for old, new in EDITS.get(n, []):
        if old not in body:
            raise SystemExit(f"v04 copy: slide {n}: text not found: {old[:60]}")
        body = body.replace(old, new)
    sl["body"] = body
    if n in LABELS:
        sl["label"] = LABELS[n]
    if n in NOTES:
        sl["notes"] = NOTES[n]


