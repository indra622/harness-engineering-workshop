def excerpt(sid, plain):
    """The v10 block with lecture-time lines removed, everything else verbatim."""
    for old, new in EXCERPT_CUTS.get(sid, []):
        if old not in plain:
            raise SystemExit(f"v04 excerpt: S{sid}: text not found: {old[:60]}")
        plain = plain.replace(old, new)
    out = []
    for i, line in enumerate(plain.splitlines()):
        if i == 0:
            line = re.sub(r" \(\d+분부터 \d+분까지, \d+분\)$", "", line)
        if line.startswith("시간:"):
            continue
        out.append(line)
    return re.sub(r"\n{3,}", "\n\n", "\n".join(out)).strip()


